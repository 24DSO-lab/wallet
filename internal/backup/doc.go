// Зона Dev 3 (docs/TEAM-PROMPTS.md, раздел 2). Каркас создан Dev 1 в PR #0.
//
// # Что в архиве
//
// Zip-архив с записями только этих видов и ничем больше:
//
//	manifest.json        формат, время, версия схемы, размер и SHA-256 каждого файла
//	db/wallet.db         согласованный снимок БД (VACUUM INTO), сделанный при открытом приложении
//	keystore/<имя>       файлы keystore ровно такими, как лежат на диске
//
// Keystore не расшифровывается: пароль пакет не получает. Парольная фраза BIP39
// нигде не хранится и в архив попасть не может. Рядом с архивом лежит файл
// <архив>.sha256 с контрольной суммой всего архива (формат sha256sum).
//
// # Создание
//
// Архив собирается во временном каталоге внутри целевого и появляется под
// конечным именем атомарно (переименованием), сначала файл контрольной суммы,
// потом архив: если есть архив, есть и его сумма. Существующие файлы не
// перезаписываются. Отмена контекста не оставляет временных файлов.
//
// # Восстановление
//
// Порядок проверок: контрольная сумма архива, список записей (только
// разрешённые имена, никаких путей наружу, ссылок и каталогов), манифест
// (формат, версия схемы, совпадение с записями), распаковка во временный
// каталог рядом с рабочими данными с проверкой размера и SHA-256 каждого файла,
// разбор заголовка каждого keystore-файла (CheckKeystoreFile, пароль не нужен),
// заголовок SQLite. Только после этого рабочие данные заменяются, причём
// прежние не удаляются, а уходят в каталог pre-restore-<время> внутри
// DataDir. При любой ошибке замена откатывается, рабочие данные остаются
// нетронутыми. Пароль после восстановления проверяет вызывающий через
// Keystore.Verify.
//
// # Требования к вызывающему (Dev 7)
//
//   - Перед Restore база должна быть закрыта (store.DB.Close): на Windows
//     открытый файл нельзя заменить, и замена откатится с ошибкой. После Restore
//     базу открывают заново.
//   - Create и операции, переписывающие keystore (ChangePassword, Save, Delete),
//     не должны идти одновременно: архив мог бы получить файлы с разными паролями.
//     Пакет это не обеспечивает, нужна общая блокировка в сервисе.
//   - Restore нельзя прервать после начала замены (это несколько быстрых
//     переименований); отмена контекста действует до этого момента.
