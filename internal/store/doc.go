// Зона Dev 3 (docs/TEAM-PROMPTS.md, раздел 2). Каркас создан Dev 1 в PR #0.
//
// # Устройство
//
// Драйвер modernc.org/sqlite (без CGO). Файл базы открывается двумя пулами
// соединений: писатель (одно соединение, WAL, внешние ключи, busy_timeout,
// synchronous=FULL) и читатели (query_only). В режиме WAL чтение идёт
// параллельно с записью и не блокирует её. Миграции встроены в бинарник
// (migrations/*.sql), версия схемы лежит в PRAGMA user_version, каждая
// миграция выполняется в своей транзакции.
//
// # Правила для вызывающего
//
//   - Внутри WithTx работайте только с переданным tx, а не с исходным
//     хранилищем: писатель один, обращение к исходному хранилищу из fn будет
//     ждать завершения этой же транзакции, то есть зависнет до отмены ctx.
//   - Суммы это domain.Amount; в БД они текст из цифр. Времена хранятся с
//     точностью до миллисекунды в UTC.
//   - Отсутствие записи это domain.ErrNotFound (через errors.Is).
//   - Изменение схемы это только новый файл миграции, существующие
//     не правятся.
//
// База считается приватным файлом: там лежит xpub, раскрывающий все адреса
// кошелька. Файл создаётся с правами 0600.
